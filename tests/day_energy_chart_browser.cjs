const {chromium}=require('playwright');
const fs=require('fs'),os=require('os'),path=require('path');
(async()=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'jarvis-chart-'));
 for(const name of ['index.html','demo.js'])fs.copyFileSync(`testing/lab-public/energy/${name}`,path.join(root,name));
 fs.copyFileSync('managed_sources/energy_weather/power-sun.js',path.join(root,'power-sun.js'));
 const b=await chromium.launch({headless:true}),p=await b.newPage({viewport:{width:1100,height:800}}),errors=[];
 p.on('pageerror',e=>errors.push(e.message));
 try{
  await p.goto('file://'+path.join(root,'index.html'));const c=p.locator('jarvis-power-sun');await c.locator('.scrub').waitFor();
  await c.locator('[data-line="0"]').click();if(await c.locator('[data-line="0"]').getAttribute('aria-pressed')!=='false')throw Error('toggle');
  await c.locator('[data-line="0"]').click();const hit=await c.locator('.hit').boundingBox();await p.mouse.move(hit.x+hit.width*.5,hit.y+50);
  if(!(await c.locator('.readout').textContent()).includes('12:00'))throw Error('midday hover: '+await c.locator('.readout').textContent());
  const slider=c.locator('.scrub');await slider.evaluate(e=>{e.value=e.max;e.dispatchEvent(new Event('input',{bubbles:true}));});
  if(!(await c.locator('.readout').textContent()).includes('24:00'))throw Error('end time');
  if(!(await c.locator('[data-value="0"]').textContent()).includes('—'))throw Error('future reading');
  await slider.focus();await p.evaluate(()=>{const c=document.querySelector('jarvis-power-sun');c.hass=c.h;});
  if(!await slider.evaluate(e=>e===e.getRootNode().activeElement))throw Error('slider focus after HA update');
  await c.locator('[data-line="1"]').focus();await p.keyboard.press('Enter');
  if(!await c.locator('[data-line="1"]').evaluate(e=>e===e.getRootNode().activeElement))throw Error('toggle focus');
  if(await c.locator('.solar-peak').count()!==1)throw Error('geometric peak dot missing');
  if(!(await c.locator('.weather-location').textContent()).includes('Žitenice'))throw Error('weather locality missing');
  if(await c.locator('.weather-cell').count()<3)throw Error('weather strip missing');
  if(!(await c.locator('.weather-strip').textContent()).includes('°'))throw Error('weather temperatures missing');
  if(await c.locator('[data-line]').count()!==6)throw Error('six curves');
  if(!(await c.locator('[data-value="3"]').textContent()).includes('%'))throw Error('battery unit');
  if(!(await c.locator('[data-value="4"]').textContent()).includes('Kč/kWh'))throw Error('spot unit');
  const dateBefore=await c.locator('.date').inputValue();
  await c.locator('[data-day=prev]').click();await p.waitForFunction(d=>document.querySelector('jarvis-power-sun').selectedDate!==d,dateBefore);
  if(await c.locator('.date').inputValue()===dateBefore)throw Error('previous day');
  await c.locator('[data-day=today]').click();await c.locator('[data-day=next]').click();
  const range=c.locator('.scrub');await range.evaluate(e=>{e.value=Number(e.max)/2;e.dispatchEvent(new Event('input',{bubbles:true}));});
  if(!(await c.locator('[data-value="3"]').textContent()).includes('—'))throw Error('future battery fabricated');
  if((await c.locator('[data-value="4"]').textContent()).includes('—'))throw Error('published future price missing');
  await c.locator('.date').fill('2026-01-12');await c.locator('.date').press('Tab');
  if(await c.locator('.date').inputValue()!=='2026-01-12')throw Error('date picker');
  await c.locator('[data-day=today]').click();
  await c.locator('[data-period=week]').click();await c.locator('.energy-summary').waitFor();
  if(!(await c.locator('h2').textContent()).includes('Týden'))throw Error('week view');
  if(await c.locator('.period-solar-peak').count()!==7)throw Error('one solar planning dot per day missing');
  const periodHit=await c.locator('.period-hit').boundingBox();await p.mouse.move(periodHit.x+periodHit.width*.4,periodHit.y+40);
  if(!(await c.locator('.period-readout').textContent()).includes('.'))throw Error('Czech hover date missing');
  if(!(await c.locator('[data-energy-value="0"]').textContent()).includes('kWh'))throw Error('instant hover values');
  await c.locator('[data-energy="0"]').click();if(await c.locator('[data-energy="0"]').getAttribute('aria-pressed')!=='false')throw Error('period series toggle');
  await c.locator('.period-scrub').focus();await p.keyboard.press('ArrowRight');
  await c.locator('[data-period=month]').click();await p.setViewportSize({width:390,height:844});if(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('monthly mobile overflow');
  await p.setViewportSize({width:1100,height:800});
  await c.locator('[data-period=year]').click();if(!(await c.locator('h2').textContent()).includes('Rok'))throw Error('year view');
  await c.locator('[data-period=day]').click();await c.locator('.weather-inline').first().waitFor();
  if(await c.locator('.weather-inline b').count()<3)throw Error('compact temperatures');
  await p.setViewportSize({width:390,height:844});
  if(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('mobile overflow');
  if(errors.length)throw Error(errors.join('\n'));console.log('Browser passed: hover, toggle, future, keyboard focus, mobile');
 }finally{await b.close();fs.rmSync(root,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exit(1)});
